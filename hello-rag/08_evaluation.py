# $ venv/bin/python hello-rag/08_evaluation.py
#
# Goal: "does the RAG pipeline actually work" needs a real, repeatable
# answer, not eyeballing a few example outputs — the same reason unit tests
# exist. A minimal RAG eval needs a small labeled set (question -> what the
# right answer/source should contain) and two separate checks:
#   - retrieval: did the relevant chunk even make it into the top k?
#     (if not, generation never had a chance — this isolates WHICH stage
#     failed instead of just "the final answer was wrong")
#   - generation: given that context, did the answer actually contain the
#     expected fact?
# Step 8: A minimal labeled eval set, checking retrieval hit-rate and generation accuracy separately

from langchain_core.documents import Document
from langchain_core.prompts import ChatPromptTemplate
from langchain_core.vectorstores import InMemoryVectorStore
from langchain_ollama import ChatOllama, OllamaEmbeddings

embeddings = OllamaEmbeddings(model="nomic-embed-text")
llm = ChatOllama(model="llama3.2:3b", temperature=0)

documents = [
    Document("Our office is located at 123 Market Street, Suite 400, San Francisco."),
    Document("Support tickets are answered within 24 hours on business days."),
    Document("The API rate limit is 100 requests per minute per API key."),
    Document("Refunds take 5-7 business days to appear on your statement."),
    Document("We support Python, JavaScript, and Go SDKs."),
]

vector_store = InMemoryVectorStore(embeddings)
vector_store.add_documents(documents)

prompt = ChatPromptTemplate.from_messages(
    [("system", "Answer using ONLY the given context, in one short sentence."), ("human", "Context:\n{context}\n\nQuestion: {question}")]
)

# Each case: the question, a substring expected somewhere in the RETRIEVED
# context (checks retrieval), and a substring expected in the final ANSWER
# (checks generation, given retrieval succeeded).
eval_set = [
    {"question": "What's the API rate limit?", "expected_in_context": "100 requests", "expected_in_answer": "100"},
    {"question": "How long do refunds take?", "expected_in_context": "5-7 business days", "expected_in_answer": "5-7"},
    {"question": "Where is your office?", "expected_in_context": "Market Street", "expected_in_answer": "Market"},
    {"question": "Do you support Rust?", "expected_in_context": "Python, JavaScript, and Go", "expected_in_answer": None},
]


def run_case(case: dict, k: int = 2) -> dict:
    retrieved = vector_store.similarity_search(case["question"], k=k)
    context = "\n".join(doc.page_content for doc in retrieved)
    retrieval_hit = case["expected_in_context"] in context

    response = (prompt | llm).invoke({"context": context, "question": case["question"]}).content
    if case["expected_in_answer"] is None:
        # No fact SHOULD be in the answer (e.g. asking about something the
        # docs don't cover) — a good answer says so instead of guessing.
        generation_ok = any(phrase in response.lower() for phrase in ["don't", "not", "no information", "doesn't"])
    else:
        generation_ok = case["expected_in_answer"].lower() in response.lower()

    return {"retrieval_hit": retrieval_hit, "generation_ok": generation_ok, "answer": response}


results = [run_case(case) for case in eval_set]

print(f"{'question':<35} {'retrieval':<10} {'generation':<11} answer")
for case, result in zip(eval_set, results):
    r = "✓" if result["retrieval_hit"] else "✗"
    g = "✓" if result["generation_ok"] else "✗"
    print(f"{case['question']:<35} {r:<10} {g:<11} {result['answer'][:60]!r}")

retrieval_rate = sum(r["retrieval_hit"] for r in results) / len(results)
generation_rate = sum(r["generation_ok"] for r in results) / len(results)
print(f"\nretrieval hit-rate: {retrieval_rate:.0%}  ({sum(r['retrieval_hit'] for r in results)}/{len(results)})")
print(f"generation accuracy: {generation_rate:.0%}  ({sum(r['generation_ok'] for r in results)}/{len(results)})")

